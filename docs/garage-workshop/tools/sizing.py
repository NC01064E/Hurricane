#!/usr/bin/env python3
"""Hand cooling-load estimate for the 19x12 ft conditioned room, to size the mini-split. NOT a Manual J.
Writes ../SIZING.md. All inputs are assumptions stated in the table; change them and re-run."""
import os
OUT = os.path.join(os.path.dirname(__file__), "..")
T_IN = 75
# (component, description, area/qty, U-or-R basis, delta-T or factor, BTU/h)
rows = []
def add(name, why, btu, group): rows.append((name, why, round(btu), group))
# envelope: BTU/h = area / R * dT
add("Ceiling", "228 sf, R-30 batts (~R-27 effective), attic ~130 F (dT 55)", 228/27*55, "envelope")
add("Partition to storage strip", "152 sf incl. leaves, ~R-11, strip ~100 F (dT 25)", 152/11*25, "envelope")
add("Two exterior block walls", "171 sf net of door, uninsulated CMU ~R-2.2, sun-heated (dT 30)", 171/2.2*30, "envelope")
add("Exterior door", "21 sf, ~R-3 (dT 16)", 21/3*16, "envelope")
add("Slab", "allowance", 100, "envelope")
add("Infiltration (sensible + latent)", "0.3 ACH on 1,824 cf = 9 cfm", 1.08*9.1*16 + 0.68*9.1*50, "envelope")
# internal gains
add("Two people exercising", "~900 BTU/h each", 1800, "workout")
add("Treadmill motor", "~800 W electrical while running", 800*3.412, "workout")
add("Computer towers (2)", "~250 W", 250*3.412, "always")
add("LED panels (4 x 39 W)", "156 W", 156*3.412, "always")
add("Water heater standby", "~70 W average to the room", 70*3.412, "always")
add("Fans (2 x 30 W) + TV (100 W)", "160 W", 160*3.412, "always")
env = sum(r[2] for r in rows if r[3] == "envelope")
alw = sum(r[2] for r in rows if r[3] == "always")
wrk = sum(r[2] for r in rows if r[3] == "workout")
idle, peak = env + alw, env + alw + wrk
md = ["# Mini-split sizing (hand estimate)\n",
 "> A first-pass estimate to choose between 12K and 18K. It is **not a Manual J**. Assumptions: Fort Lauderdale summer design (~91 F outdoor, 75 F indoor, attic ~130 F), the insulated ceiling and partition from the plan, and the exterior block walls and door as they are today. Generated by `tools/sizing.py`.\n",
 "| Component | Basis | BTU/h |\n|---|---|---|"]
md += [f"| {n} | {w} | {b:,} |" for n, w, b, g in rows]
md += [f"| **Idle (envelope + always-on gains)** | | **{idle:,}** |",
       f"| **Peak (idle + workout in progress)** | | **{peak:,}** |\n",
       "## Result\n",
       f"- **12,000 BTU/h** covers the worst-case peak (~{peak:,} BTU/h, about {peak/12000:.0%} of rated capacity) and has margin for the extra heat the estimate ignores.",
       f"- At idle (~{idle:,} BTU/h) the room needs well under half of a 12K unit. A 12K inverter modulates down to roughly 3,000-4,000 BTU/h, (typical for inverter units; check the spec sheet), so it can run long and steady at idle, which is what dehumidifying steel storage needs.",
       "- An 18K unit's minimum output is roughly 5,000-6,000 BTU/h (typical for inverter mini-splits; check the spec sheet), about the whole idle load. It would cycle on and off at idle, which is the short-cycling the plan itself warns against.",
       "- **Do not go to 9K:** the peak load, not idle, sets the size, and 9K would run flat out through a workout.\n",
       "## What would change the answer\n",
       "- The uninsulated block walls are the biggest single envelope item (about a fifth of the peak, nearly 40% of idle). Insulating or shading them would cut the peak by roughly 1,000-1,500 BTU/h; 12K is the right call either way.",
       "- A west-facing exterior wall, a larger exterior door, or a third person working out regularly moves the peak toward the top of 12K's range.",
       "- A heat pump's rated capacity falls as outdoor temperature rises; 12,000 BTU/h is the rating at 95 F. If an installer's Manual J exceeds about 11,500 BTU/h, revisit.\n"]
open(os.path.join(OUT, "SIZING.md"), "w").write("\n".join(md) + "\n")
print(f"idle {idle:,}  peak {peak:,}  ({peak/12000:.0%} of 12K)  block walls {rows[2][2]:,} ({rows[2][2]/peak:.0%} of peak)")
